#!/usr/bin/env python3
"""Generate gen/*.c and gen/*.h from the verbatim Linux sources in linux/.

Everything in gen/ is either a whole upstream file with only its kernel
#include lines removed, or upstream functions copied byte-for-byte by
tools/extract.py. The only edits to upstream code are listed in PATCHES
below, each with the reason.
"""
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
L = os.path.join(ROOT, 'linux')
G = os.path.join(ROOT, 'gen')
os.makedirs(G, exist_ok=True)

HDR = '/* GENERATED by tools/gen.py from Linux kernel sources - do not edit.\n' \
      ' * SPDX-License-Identifier: GPL-2.0-or-later */\n'


def strip_kernel_includes(text):
    return re.sub(r'^#include\s*<[^>]+>\s*\n', '', text, flags=re.M)


def extract(fname, funcs):
    out = subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'extract.py'),
                          os.path.join(L, fname)] + funcs,
                         check=True, capture_output=True, text=True)
    return out.stdout


def write(name, text):
    with open(os.path.join(G, name), 'w') as f:
        f.write(HDR + text)


def patch(text, old, new, why):
    if old not in text:
        raise SystemExit(f'patch failed ({why}): pattern not found')
    return text.replace(old, new, 1)


# ---------------------------------------------------------------- headers
for hname in ['cx231xx-reg.h', 'cx231xx-conf-reg.h', 'cx231xx-dif.h',
              'cx231xx-pcb-cfg.h', 'cx25840.h']:
    write(hname, strip_kernel_includes(open(os.path.join(L, hname)).read()))
h = open(os.path.join(L, 'cx231xx.h')).read()
h = strip_kernel_includes(h)
h = patch(h, '#define _CX231XX_H\n',
          '#define _CX231XX_H\n#include "kstubs.h"\n#include "cx25840.h"\n',
          'pull in the userspace kernel shim')
# struct cx231xx_audio has members we do not need that use kernel types by value
write('cx231xx.h', h)

ch = open(os.path.join(L, 'cx25840-core.h')).read()
ch = strip_kernel_includes(ch)
ch = patch(ch, '#define _CX25840_CORE_H_\n',
           '#define _CX25840_CORE_H_\n#include "kstubs.h"\n#include "cx25840.h"\n'
           'struct v4l2_vbi_format; struct v4l2_sliced_vbi_format;\n'
           'struct v4l2_decode_vbi_line; struct v4l2_ctrl_ops; struct v4l2_subdev_ir_ops;\n',
           'pull in the userspace kernel shim')
write('cx25840-core.h', ch)

# ---------------------------------------------------------------- whole files
for src, dst in [('cx231xx-avcore.c', 'avcore.c'), ('cx231xx-pcb-cfg.c', 'pcb_cfg.c')]:
    t = strip_kernel_includes(open(os.path.join(L, src)).read())
    write(dst, t)

# ---------------------------------------------------------------- core + i2c
core_funcs = [
    'cx231xx_send_usb_command', '__usb_control_msg', 'cx231xx_read_ctrl_reg',
    'cx231xx_send_vendor_cmd', 'cx231xx_write_ctrl_reg',
    'cx231xx_set_video_alternate', 'cx231xx_set_alt_setting', 'cx231xx_gpio_set',
    'cx231xx_set_mode', 'cx231xx_dev_init', 'cx231xx_send_gpio_cmd',
    'cx231xx_mode_register', 'cx231xx_read_i2c_master', 'cx231xx_write_i2c_master',
    'cx231xx_read_i2c_data', 'cx231xx_write_i2c_data', 'cx231xx_reg_mask_write',
    'cx231xx_read_modify_write_i2c_dword', 'cx231xx_set_field',
]
i2c_funcs = [
    'get_real_i2c_port', 'is_tuner', 'cx231xx_i2c_send_bytes', 'cx231xx_i2c_recv_bytes',
    'cx231xx_i2c_recv_bytes_with_saddr', 'cx231xx_i2c_check_for_device',
    'cx231xx_i2c_xfer',
]
core = '#include "cx231xx.h"\n\n' + extract('cx231xx-core.c', core_funcs) \
    + extract('cx231xx-i2c.c', i2c_funcs)
core += '''
/* ---- glue (not upstream): kernel i2c_transfer()/i2c_master_send() entry
 * points, routed to the upstream cx231xx I2C algorithm above ---- */
int i2c_transfer(struct i2c_adapter *adap, struct i2c_msg *msgs, int num)
{
	return cx231xx_i2c_xfer(adap, msgs, num);
}

int i2c_master_send(const struct i2c_client *client, const char *buf, int count)
{
	struct i2c_msg msg = { client->addr, 0, (u16)count, (u8 *)buf };
	int ret = i2c_transfer(client->adapter, &msg, 1);
	return ret == 1 ? count : (ret < 0 ? ret : -EIO);
}
'''
write('core_port.c', core)

# ---------------------------------------------------------------- video parser
video_funcs = [
    'print_err_status', 'buffer_filled', 'get_next_buf', 'cx231xx_isoc_copy',
    'cx231xx_bulk_copy', 'cx231xx_find_boundary_SAV_EAV', 'cx231xx_find_next_SAV_EAV',
    'cx231xx_get_video_line', 'cx231xx_copy_video_line', 'cx231xx_reset_video_buffer',
    'cx231xx_do_copy', 'cx231xx_swab', 'cx231xx_is_buffer_done', 'video_mux',
]
video = '#include "cx231xx.h"\n\n' + extract('cx231xx-video.c', video_funcs) + '''
/* ---- glue (not upstream): non-static entry points for the app ---- */
int port_isoc_copy(struct cx231xx *dev, struct urb *urb) { return cx231xx_isoc_copy(dev, urb); }
int port_bulk_copy(struct cx231xx *dev, struct urb *urb) { return cx231xx_bulk_copy(dev, urb); }
'''
write('video_port.c', video)

# ---------------------------------------------------------------- board table + card setup
cards = open(os.path.join(L, 'cx231xx-cards.c')).read()
i = cards.index('\t[CX231XX_BOARD_HAUPPAUGE_USBLIVE2] = {')
j = cards.index('\n\t},\n', i) + len('\n\t},\n')
board = cards[i:j]
write('cards_port.c', '#include "cx231xx.h"\n\n'
      '/* ---- verbatim from linux cx231xx-cards.c: the USB-Live2 board entry ---- */\n'
      'struct cx231xx_board cx231xx_boards[] = {\n' + board + '};\n\n'
      + extract('cx231xx-cards.c', ['cx231xx_set_model', 'cx231xx_pre_card_setup', 'cx231xx_config_i2c']))

# ---------------------------------------------------------------- cx25840 decoder
cx_funcs = [
    'cx25840_write', 'cx25840_write4', 'cx25840_read', 'cx25840_read4',
    'cx25840_and_or', 'cx25840_and_or4', 'cx231xx_initialize', 'cx25840_std_setup',
    'input_change', 'set_input', 'set_v4lstd', 'cx25840_s_ctrl', 'cx25840_set_fmt',
    'cx25840_s_std', 'cx25840_s_video_routing', 'cx25840_s_stream',
    'cx25840_reset', 'cx25840_load_fw',
]
cx = extract('cx25840-core.c', cx_funcs)
# PATCH 1: cx231xx_initialize() loads the cx231xx audio-DSP firmware through a
# kernel workqueue. That firmware only drives TV-tuner audio (BTSC/NICAM);
# the USB-Live2 has no tuner, and its line-in audio does not use it. Replace
# the workqueue block with a hook so it can be added later if ever needed.
cx = patch(cx, '\tDEFINE_WAIT(wait);\n', '', 'drop workqueue wait')
cx = patch(cx, '\tstruct workqueue_struct *q;\n', '', 'drop workqueue decl')
start = cx.index('\t/*\n\t * Do the firmware load in a work handler')
end = cx.index('destroy_workqueue(q);\n\t}\n', start) + len('destroy_workqueue(q);\n\t}\n')
cx = cx[:start] + '\tcx25840_fw_load_hook(client); /* PATCH 1, see tools/gen.py */\n' + cx[end:]
# cx23888-only helpers referenced from shared code paths (never reached on cx231xx)
pre = ('#include "cx25840-core.h"\n\n'
       'void cx25840_fw_load_hook(struct i2c_client *client);\n'
       'static void cx23888_std_setup(struct i2c_client *client) { (void)client; }\n'
       'static void cx25840_vconfig_add(struct cx25840_state *s, u32 c) { (void)s; (void)c; }\n'
       'static void cx25840_vconfig_apply(struct i2c_client *c) { (void)c; }\n'
       '/* other chips in the cx25840 family: never reached on the CX23102 */\n'
       'static void cx25836_initialize(struct i2c_client *c) { (void)c; }\n'
       'static void cx23885_initialize(struct i2c_client *c) { (void)c; }\n'
       'static void cx25840_initialize(struct i2c_client *c) { (void)c; }\n'
       'static int set_input(struct i2c_client *client, enum cx25840_video_input vid_input,\n'
       '                     enum cx25840_audio_input aud_input);\n\n')
audio = extract('cx25840-audio.c', ['cx25840_set_audclk_freq', 'cx25836_set_audclk_freq',
                                    'cx23885_set_audclk_freq', 'cx231xx_set_audclk_freq',
                                    'set_audclk_freq', 'cx25840_audio_set_path'])
glue = r'''
/* ---- glue (not upstream) ------------------------------------------------
 * Userspace equivalent of cx25840_probe(): the hardware-touching steps are
 * the same as upstream (read the chip id, set the state defaults, apply the
 * picture-control defaults that v4l2_ctrl_handler_setup() would apply). */
static struct cx25840_state port_state;

struct v4l2_subdev *port_cx25840_probe(struct i2c_client *client)
{
	struct cx25840_state *state = &port_state;
	struct v4l2_ctrl ctrl;
	u16 device_id;
	int default_volume;

	device_id = cx25840_read(client, 0x101) << 8;
	device_id |= cx25840_read(client, 0x100);
	fprintf(stderr, "[cx25840] A/V decoder device_id = 0x%04x\n", device_id);
	if ((device_id & 0xfff0) != 0x5A30) {
		v4l_err(client, "not a cx231xx built-in A/V decoder (id 0x%04x)\n", device_id);
		return NULL;
	}

	memset(state, 0, sizeof(*state));
	state->sd.client = client;
	client->clientdata = &state->sd;
	state->c = client;
	state->vid_input = CX25840_COMPOSITE7;
	state->aud_input = CX25840_AUDIO8;
	state->audclk_freq = 48000;
	state->audmode = V4L2_TUNER_MODE_LANG1;
	state->vbi_line_offset = 8;
	state->id = CX2310X_AV;
	state->rev = device_id;
	state->vbi_regs_offset = 0;
	state->std = V4L2_STD_NTSC_M;

	/* v4l2_ctrl_handler_setup(): apply default picture controls */
	ctrl.handler = &state->hdl;
	ctrl.id = V4L2_CID_BRIGHTNESS; ctrl.val = 128; cx25840_s_ctrl(&ctrl);
	ctrl.id = V4L2_CID_CONTRAST;   ctrl.val = 64;  cx25840_s_ctrl(&ctrl);
	ctrl.id = V4L2_CID_SATURATION; ctrl.val = 64;  cx25840_s_ctrl(&ctrl);
	ctrl.id = V4L2_CID_HUE;        ctrl.val = 0;   cx25840_s_ctrl(&ctrl);

	/* volume clamp, as in upstream probe */
	default_volume = cx25840_read(client, 0x8d4);
	if (default_volume > 228)
		cx25840_write(client, 0x8d4, 228);
	else if (default_volume < 20)
		cx25840_write(client, 0x8d4, 20);

	return &state->sd;
}

int port_cx25840_set_ctrl(struct v4l2_subdev *sd, u32 id, s32 val)
{
	struct v4l2_ctrl ctrl;
	ctrl.handler = &to_state(sd)->hdl;
	ctrl.id = id;
	ctrl.val = val;
	return cx25840_s_ctrl(&ctrl);
}

/* returns gen_stat2 bit 5 (video present) and the detected format, as in
 * upstream log_video_status() */
int port_cx25840_video_status(struct v4l2_subdev *sd, int *present, int *fmt)
{
	struct i2c_client *client = v4l2_get_subdevdata(sd);
	u8 gen_stat1 = cx25840_read(client, 0x40d);
	u8 gen_stat2 = cx25840_read(client, 0x40e);
	*present = (gen_stat2 & 0x20) ? 1 : 0;
	*fmt = gen_stat1 & 0xf;
	return 0;
}

int subdev_video_s_routing(struct v4l2_subdev *sd, u32 input, u32 output, u32 config)
{ return cx25840_s_video_routing(sd, input, output, config); }
int subdev_video_s_std(struct v4l2_subdev *sd, u64 std) { return cx25840_s_std(sd, std); }
int subdev_video_s_stream(struct v4l2_subdev *sd, int enable) { return cx25840_s_stream(sd, enable); }
int subdev_pad_set_fmt(struct v4l2_subdev *sd, void *st, struct v4l2_subdev_format *fmt)
{ return cx25840_set_fmt(sd, st, fmt); }
int subdev_core_load_fw(struct v4l2_subdev *sd) { return cx25840_load_fw(sd); }
'''
write('cx25840_port.c', pre + audio + cx + glue)
print('generated', sorted(os.listdir(G)))
